function orderGalleryProjects(projectList) {
    return [...projectList].sort((a, b) => {
        if (projectIsLatest(a) !== projectIsLatest(b)) {
            return projectIsLatest(a) ? -1 : 1;
        }

        return a.id - b.id;
    });
}

function shuffleGalleryProjects(projectList) {
    const shuffledProjects = [...projectList];

    for (let i = shuffledProjects.length - 1; i > 0; i -= 1) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffledProjects[i], shuffledProjects[j]] = [shuffledProjects[j], shuffledProjects[i]];
    }

    return shuffledProjects;
}

function getMobileShuffledProjects() {
    if (!mobileShuffledProjects) {
        mobileShuffledProjects = shuffleGalleryProjects(orderGalleryProjects(projects));
    }

    return mobileShuffledProjects;
}

function getDesktopShuffledProjects() {
    if (!desktopShuffledProjects) {
        desktopShuffledProjects = shuffleGalleryProjects(projects);
    }

    return desktopShuffledProjects;
}

function getProjectAspectRatio(project) {
    const fileName = project.image?.split("/").pop() || "";

    if (project.aspectRatio) return project.aspectRatio;
    if (project.width && project.height) return project.width / project.height;
    if (project.height) return 4 / 3;
    if (fileName.includes("poster")) return 0.72;
    if (fileName.includes("variation")) return 1;
    if (fileName.includes("promo")) return 1;
    if (fileName.includes("banner")) return 1.8;

    return 1.4;
}

function getProjectRatioGroup(project) {
    const ratio = getProjectAspectRatio(project);

    if (ratio < 0.86) return "tall";
    if (ratio > 1.18) return "wide";

    return "square";
}

function setGalleryImageRatio(image) {
    const shell = image.closest(".gallery-image-shell");

    if (!shell || !image.naturalWidth || !image.naturalHeight) return;

    shell.style.aspectRatio = `${image.naturalWidth} / ${image.naturalHeight}`;

    const elapsed = performance.now() - Number(shell.dataset.skeletonStarted || 0);
    const remainingTime = Math.max(0, gallerySkeletonMinTime - elapsed);

    window.setTimeout(() => {
        shell.classList.add("is-loaded");
    }, remainingTime);
}

function prepareGalleryImage(image) {
    if (!image) return;

    const shell = image.closest(".gallery-image-shell");

    if (shell) {
        shell.dataset.skeletonStarted = String(performance.now());
    }

    if (image.complete && image.naturalWidth) {
        setGalleryImageRatio(image);
        return;
    }

    image.addEventListener("load", () => {
        setGalleryImageRatio(image);
    }, { once: true });

    image.addEventListener("error", () => {
        shell?.classList.add("is-loaded");
    }, { once: true });
}

