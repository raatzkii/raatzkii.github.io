function shuffle(array) {
    return [...array].sort(() => Math.random() - 0.5);
}

function moveIndicator(activeChip) {
    if (!activeChip) return;

    const filtersRect = filters.getBoundingClientRect();
    const activeRect = activeChip.getBoundingClientRect();

    indicator.style.width = `${activeChip.offsetWidth}px`;
    indicator.style.height = `${activeChip.offsetHeight}px`;
    indicator.style.transform = `translate(${activeRect.left - filtersRect.left}px, ${activeRect.top - filtersRect.top}px)`;
}

function getProjectById(projectId) {
    return projects.find(project => project.id === projectId);
}

function projectMatchesFilter(project, filter) {
    if (filter === "all") return true;
    return (project.categories || [project.category]).includes(filter);
}

function getProjectAspectRatio(project) {
    const fileName = project.image?.split("/").pop() || "";

    if (project.aspectRatio) return project.aspectRatio;
    if (project.width && project.height) return project.width / project.height;
    if (project.height) return 4 / 3;
    if (fileName.includes("poster")) return 0.72;
    if (fileName.includes("variation")) return 1;
    if (fileName.includes("promo")) return 1;
    if (fileName.includes("banner")) return 1.8;

    return 1.4;
}

function setGalleryImageRatio(image) {
    const shell = image.closest(".gallery-image-shell");

    if (!shell || !image.naturalWidth || !image.naturalHeight) return;

    shell.style.aspectRatio = `${image.naturalWidth} / ${image.naturalHeight}`;

    const elapsed = performance.now() - Number(shell.dataset.skeletonStarted || 0);
    const remainingTime = Math.max(0, gallerySkeletonMinTime - elapsed);

    window.setTimeout(() => {
        shell.classList.add("is-loaded");
    }, remainingTime);
}

